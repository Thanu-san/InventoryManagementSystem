package com.stockflow.controller;

import com.stockflow.model.Product;
import com.stockflow.model.PurchaseOrder;
import com.stockflow.model.PurchaseOrderItem;
import com.stockflow.model.PurchaseOrderStatus;
import com.stockflow.model.Supplier;
import com.stockflow.repository.InMemoryInventoryTransactionRepository;
import com.stockflow.repository.InMemoryProductRepository;
import com.stockflow.repository.InMemoryPurchaseOrderReceiptRepository;
import com.stockflow.repository.InMemoryPurchaseOrderReportRepository;
import com.stockflow.repository.InMemoryPurchaseOrderRepository;
import com.stockflow.repository.InMemorySupplierRepository;
import com.stockflow.repository.InMemorySupplierReturnRepository;
import com.stockflow.service.PurchaseOrderService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.PrintStream;
import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Scanner;

import static org.junit.jupiter.api.Assertions.*;

@DisplayName("PurchaseOrderController Console Tests")
class PurchaseOrderControllerTest {

    private InMemoryPurchaseOrderRepository poRepository;
    private InMemorySupplierRepository supplierRepository;
    private InMemoryProductRepository productRepository;
    private InMemoryInventoryTransactionRepository transactionRepository;
    private InMemoryPurchaseOrderReceiptRepository receiptRepository;
    private InMemoryPurchaseOrderReportRepository reportRepository;
    private InMemorySupplierReturnRepository returnRepository;
    private PurchaseOrderService poService;

    @BeforeEach
    void setUp() {
        poRepository = new InMemoryPurchaseOrderRepository();
        supplierRepository = new InMemorySupplierRepository();
        productRepository = new InMemoryProductRepository();
        transactionRepository = new InMemoryInventoryTransactionRepository(productRepository);
        receiptRepository = new InMemoryPurchaseOrderReceiptRepository(poRepository, productRepository, transactionRepository);
        reportRepository = new InMemoryPurchaseOrderReportRepository(poRepository, supplierRepository, receiptRepository);
        returnRepository = new InMemorySupplierReturnRepository(poRepository, receiptRepository, productRepository, transactionRepository);
        poService = new PurchaseOrderService(poRepository, supplierRepository, productRepository, receiptRepository, reportRepository, returnRepository);

        supplierRepository.save(new Supplier("SUP-01", "Global Supplier", null, null, null, null));
        productRepository.save(new Product("SKU-100", "Widget", new BigDecimal("10.00"), 50, 5));
    }

    private String runControllerWithInput(String input) {
        ByteArrayInputStream in = new ByteArrayInputStream(input.getBytes(StandardCharsets.UTF_8));
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        PrintStream originalOut = System.out;
        try {
            System.setOut(new PrintStream(out, true, StandardCharsets.UTF_8));
            PurchaseOrderController controller = new PurchaseOrderController(poService, new Scanner(in));
            controller.runMenu();
        } finally {
            System.setOut(originalOut);
        }
        return out.toString(StandardCharsets.UTF_8);
    }

    @Test
    @DisplayName("Should display menu and exit on option 12")
    void shouldExitOnOption12() {
        String output = runControllerWithInput("12\n");
        assertTrue(output.contains("--- Purchase Order Management ---"));
    }

    @Test
    @DisplayName("Should handle EOF gracefully")
    void shouldHandleEofGracefully() {
        String output = runControllerWithInput("");
        assertTrue(output.contains("--- Purchase Order Management ---"));
    }

    @Test
    @DisplayName("Should handle invalid menu choices")
    void shouldHandleInvalidMenuChoices() {
        String output = runControllerWithInput("99\n12\n");
        assertTrue(output.contains("Invalid option. Please try again."));
    }

    @Test
    @DisplayName("Should create draft purchase order with custom order number")
    void shouldCreateDraftOrderWithCustomNumber() {
        String input = String.join("\n",
                "1",             // Menu option 1: Create Draft
                "SUP-01",        // Supplier code
                "PO-TEST-101",   // Custom order number
                "12"             // Exit
        ) + "\n";

        String output = runControllerWithInput(input);
        assertTrue(output.contains("Success: Draft purchase order created successfully!"));
        assertTrue(output.contains("PO-TEST-101"));

        assertTrue(poRepository.existsByOrderNumber("PO-TEST-101"));
    }

    @Test
    @DisplayName("Should create draft purchase order with auto-generated order number")
    void shouldCreateDraftOrderWithAutoGeneratedNumber() {
        String input = String.join("\n",
                "1",        // Menu option 1: Create Draft
                "SUP-01",   // Supplier code
                "",         // Press enter for auto-generated
                "12"        // Exit
        ) + "\n";

        String output = runControllerWithInput(input);
        assertTrue(output.contains("Success: Draft purchase order created successfully!"));
        assertTrue(output.contains("Order Number: PO-"));
    }

    @Test
    @DisplayName("Should handle validation error when creating order for unknown supplier")
    void shouldHandleUnknownSupplierError() {
        String input = String.join("\n",
                "1",            // Create Draft
                "NON-EXIST",    // Supplier code
                "PO-1",         // Order number
                "12"            // Exit
        ) + "\n";

        String output = runControllerWithInput(input);
        assertTrue(output.contains("Validation Error: Supplier not found"));
    }

    @Test
    @DisplayName("Should add line item to order")
    void shouldAddLineItemToOrder() {
        poService.createDraftOrder("PO-ADD", "SUP-01");

        String input = String.join("\n",
                "2",         // Add / Update item
                "PO-ADD",    // Order number
                "SKU-100",   // SKU
                "5",         // Quantity
                "12.50",     // Unit cost
                "12"         // Exit
        ) + "\n";

        String output = runControllerWithInput(input);
        assertTrue(output.contains("Success: Line item saved successfully!"));
        assertTrue(output.contains("Line Total: $62.50"));

        PurchaseOrder order = poRepository.findByOrderNumber("PO-ADD").orElseThrow();
        assertEquals(1, order.getItems().size());
        assertEquals(new BigDecimal("62.50"), order.getTotalAmount());
    }

    @Test
    @DisplayName("Should remove line item with confirmation")
    void shouldRemoveLineItemWithConfirmation() {
        poService.createDraftOrder("PO-REM", "SUP-01");
        poService.addOrUpdateItem("PO-REM", "SKU-100", 5, new BigDecimal("10.00"));

        String input = String.join("\n",
                "3",         // Remove item
                "PO-REM",    // Order number
                "SKU-100",   // SKU
                "Y",         // Confirm
                "12"         // Exit
        ) + "\n";

        String output = runControllerWithInput(input);
        assertTrue(output.contains("Success: Product line removed successfully from purchase order."));

        PurchaseOrder order = poRepository.findByOrderNumber("PO-REM").orElseThrow();
        assertTrue(order.getItems().isEmpty());
    }

    @Test
    @DisplayName("Should cancel line item removal on N confirmation")
    void shouldCancelLineItemRemovalOnN() {
        poService.createDraftOrder("PO-NO-REM", "SUP-01");
        poService.addOrUpdateItem("PO-NO-REM", "SKU-100", 5, new BigDecimal("10.00"));

        String input = String.join("\n",
                "3",          // Remove item
                "PO-NO-REM",  // Order number
                "SKU-100",    // SKU
                "N",          // Cancel
                "12"          // Exit
        ) + "\n";

        String output = runControllerWithInput(input);
        assertTrue(output.contains("Removal cancelled."));

        PurchaseOrder order = poRepository.findByOrderNumber("PO-NO-REM").orElseThrow();
        assertEquals(1, order.getItems().size());
    }

    @Test
    @DisplayName("Should view order details with formatted lines and totals")
    void shouldViewOrderDetails() {
        poService.createDraftOrder("PO-VIEW", "SUP-01");
        poService.addOrUpdateItem("PO-VIEW", "SKU-100", 4, new BigDecimal("15.00"));

        String input = String.join("\n",
                "4",         // View order
                "PO-VIEW",   // Order number
                "12"         // Exit
        ) + "\n";

        String output = runControllerWithInput(input);
        assertTrue(output.contains("Purchase Order Details"));
        assertTrue(output.contains("PO-VIEW"));
        assertTrue(output.contains("Total Units Ordered: 4"));
        assertTrue(output.contains("Total Amount: $60.00"));
    }

    @Test
    @DisplayName("Should list purchase orders with filter")
    void shouldListOrders() {
        poService.createDraftOrder("PO-LIST-1", "SUP-01");

        String input = String.join("\n",
                "5",    // List orders
                "1",    // All
                "12"    // Exit
        ) + "\n";

        String output = runControllerWithInput(input);
        assertTrue(output.contains("PO-LIST-1"));
        assertTrue(output.contains("Total Orders Listed: 1"));
    }

    @Test
    @DisplayName("Should place purchase order with confirmation")
    void shouldPlaceOrder() {
        poService.createDraftOrder("PO-PLACE", "SUP-01");
        poService.addOrUpdateItem("PO-PLACE", "SKU-100", 10, new BigDecimal("8.00"));

        String input = String.join("\n",
                "6",         // Place order
                "PO-PLACE",  // Order number
                "Y",         // Confirm
                "12"         // Exit
        ) + "\n";

        String output = runControllerWithInput(input);
        assertTrue(output.contains("has been successfully placed!"));

        assertEquals(PurchaseOrderStatus.PLACED, poRepository.findByOrderNumber("PO-PLACE").orElseThrow().getStatus());
    }

    @Test
    @DisplayName("Should cancel purchase order with confirmation")
    void shouldCancelOrder() {
        poService.createDraftOrder("PO-CANCEL", "SUP-01");

        String input = String.join("\n",
                "7",          // Cancel order
                "PO-CANCEL",  // Order number
                "Y",          // Confirm
                "12"          // Exit
        ) + "\n";

        String output = runControllerWithInput(input);
        assertTrue(output.contains("has been cancelled."));

        assertEquals(PurchaseOrderStatus.CANCELLED, poRepository.findByOrderNumber("PO-CANCEL").orElseThrow().getStatus());
    }

    @Test
    @DisplayName("Should receive goods against purchase order through console")
    void shouldReceiveGoodsThroughConsole() {
        poService.createDraftOrder("PO-RECV-UI", "SUP-01");
        poService.addOrUpdateItem("PO-RECV-UI", "SKU-100", 10, new BigDecimal("10.00"));
        poService.placeOrder("PO-RECV-UI");

        String input = String.join("\n",
                "8",            // Option 8: Receive Goods
                "PO-RECV-UI",   // Order number
                "6",            // Receive 6 units
                "Batch #1",     // Delivery notes
                "Y",            // Confirm receiving
                "12"            // Exit
        ) + "\n";

        String output = runControllerWithInput(input);
        assertTrue(output.contains("Success: Goods successfully received!"));
        assertTrue(output.contains("Updated Purchase Order Status: PARTIALLY_RECEIVED"));

        // Product stock increased from 50 to 56
        assertEquals(56, productRepository.findBySku("SKU-100").orElseThrow().getQuantity());
    }

    @Test
    @DisplayName("Should view receiving history through console")
    void shouldViewReceivingHistoryThroughConsole() {
        poService.createDraftOrder("PO-HIST-UI", "SUP-01");
        poService.addOrUpdateItem("PO-HIST-UI", "SKU-100", 10, new BigDecimal("10.00"));
        poService.placeOrder("PO-HIST-UI");

        PurchaseOrder order = poService.getOrderByNumber("PO-HIST-UI").orElseThrow();
        Long itemId = order.getItems().get(0).getId();
        poService.receiveGoods("PO-HIST-UI", List.of(new com.stockflow.model.ReceiptLineInput(itemId, 5)), "Shipment 1");

        String input = String.join("\n",
                "9",            // Option 9: View History
                "PO-HIST-UI",   // Order number
                "12"            // Exit
        ) + "\n";

        String output = runControllerWithInput(input);
        assertTrue(output.contains("Receiving History for Order: PO-HIST-UI"));
        assertTrue(output.contains("Shipment 1"));
        assertTrue(output.contains("Total Quantity Received in this delivery: 5 units"));
    }
}
