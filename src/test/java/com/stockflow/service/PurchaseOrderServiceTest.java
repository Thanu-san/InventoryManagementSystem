package com.stockflow.service;

import com.stockflow.exception.ValidationException;
import com.stockflow.model.Product;
import com.stockflow.model.PurchaseOrder;
import com.stockflow.model.PurchaseOrderItem;
import com.stockflow.model.PurchaseOrderStatus;
import com.stockflow.model.Supplier;
import com.stockflow.repository.InMemoryProductRepository;
import com.stockflow.repository.InMemoryPurchaseOrderRepository;
import com.stockflow.repository.InMemorySupplierRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;

@DisplayName("PurchaseOrderService Business Rule Tests")
class PurchaseOrderServiceTest {

    private InMemoryPurchaseOrderRepository poRepository;
    private InMemorySupplierRepository supplierRepository;
    private InMemoryProductRepository productRepository;

    private PurchaseOrderService poService;
    private SupplierService supplierService;
    private ProductService productService;

    private Supplier supplier;
    private Product product1;
    private Product product2;

    @BeforeEach
    void setUp() {
        poRepository = new InMemoryPurchaseOrderRepository();
        supplierRepository = new InMemorySupplierRepository();
        productRepository = new InMemoryProductRepository();

        poService = new PurchaseOrderService(poRepository, supplierRepository, productRepository);
        supplierService = new SupplierService(supplierRepository, productRepository, poRepository);
        productService = new ProductService(productRepository, null, supplierRepository, poRepository);

        supplier = supplierRepository.save(new Supplier("SUP-001", "Acme Corp", "Alice", "123", "alice@acme.com", "City"));
        product1 = productRepository.save(new Product("PROD-001", "Mechanical Keyboard", new BigDecimal("79.99"), 50, 10));
        product2 = productRepository.save(new Product("PROD-002", "Wireless Mouse", new BigDecimal("29.99"), 30, 5));
    }

    @Test
    @DisplayName("Should create draft purchase order with auto-generated order number")
    void shouldCreateDraftOrderWithAutoGeneratedNumber() {
        PurchaseOrder order = poService.createDraftOrder("SUP-001");

        assertNotNull(order);
        assertNotNull(order.getId());
        assertNotNull(order.getOrderNumber());
        assertTrue(order.getOrderNumber().startsWith("PO-"));
        assertEquals(supplier.getId(), order.getSupplierId());
        assertEquals(PurchaseOrderStatus.DRAFT, order.getStatus());
        assertTrue(order.getItems().isEmpty());
    }

    @Test
    @DisplayName("Should create draft purchase order with custom order number")
    void shouldCreateDraftOrderWithCustomNumber() {
        PurchaseOrder order = poService.createDraftOrder("PO-CUSTOM-101", "SUP-001");

        assertEquals("PO-CUSTOM-101", order.getOrderNumber());
        assertEquals(supplier.getId(), order.getSupplierId());
        assertEquals(PurchaseOrderStatus.DRAFT, order.getStatus());
    }

    @Test
    @DisplayName("Should reject draft order creation with unknown supplier code")
    void shouldRejectUnknownSupplier() {
        ValidationException ex = assertThrows(ValidationException.class, () ->
                poService.createDraftOrder("NON-EXISTENT-SUP"));
        assertTrue(ex.getMessage().contains("Supplier not found"));
    }

    @Test
    @DisplayName("Should reject draft order creation with blank supplier code or order number")
    void shouldRejectBlankFieldsOnCreation() {
        assertThrows(ValidationException.class, () -> poService.createDraftOrder(null));
        assertThrows(ValidationException.class, () -> poService.createDraftOrder("   "));
        assertThrows(ValidationException.class, () -> poService.createDraftOrder(null, "SUP-001"));
        assertThrows(ValidationException.class, () -> poService.createDraftOrder("   ", "SUP-001"));
        assertThrows(ValidationException.class, () -> poService.createDraftOrder("PO-1", "   "));
    }

    @Test
    @DisplayName("Should reject duplicate order number")
    void shouldRejectDuplicateOrderNumber() {
        poService.createDraftOrder("PO-DUP-TEST", "SUP-001");

        ValidationException ex = assertThrows(ValidationException.class, () ->
                poService.createDraftOrder("PO-DUP-TEST", "SUP-001"));
        assertTrue(ex.getMessage().contains("already exists"));
    }

    @Test
    @DisplayName("Should add valid line item and snapshot product SKU and name")
    void shouldAddValidLineItemAndSnapshot() {
        PurchaseOrder order = poService.createDraftOrder("PO-LINE-1", "SUP-001");

        PurchaseOrderItem item = poService.addOrUpdateItem("PO-LINE-1", "PROD-001", 10, new BigDecimal("45.00"));

        assertNotNull(item);
        assertEquals(product1.getId(), item.getProductId());
        assertEquals("PROD-001", item.getProductSku());
        assertEquals("Mechanical Keyboard", item.getProductName());
        assertEquals(10, item.getOrderedQuantity());
        assertEquals(new BigDecimal("45.00"), item.getUnitCost());
        assertEquals(new BigDecimal("450.00"), item.getLineTotal());

        PurchaseOrder retrieved = poService.getOrderByNumber("PO-LINE-1").orElseThrow();
        assertEquals(1, retrieved.getItems().size());
        assertEquals(new BigDecimal("450.00"), retrieved.getTotalAmount());
    }

    @Test
    @DisplayName("Should reject line item for nonexistent product")
    void shouldRejectNonexistentProduct() {
        poService.createDraftOrder("PO-PROD-ERR", "SUP-001");

        ValidationException ex = assertThrows(ValidationException.class, () ->
                poService.addOrUpdateItem("PO-PROD-ERR", "NON-SKU", 5, new BigDecimal("10.00")));
        assertTrue(ex.getMessage().contains("Product not found"));
    }

    @Test
    @DisplayName("Should reject zero and negative ordered quantities")
    void shouldRejectZeroAndNegativeQuantity() {
        poService.createDraftOrder("PO-QTY-ERR", "SUP-001");

        assertThrows(ValidationException.class, () ->
                poService.addOrUpdateItem("PO-QTY-ERR", "PROD-001", 0, new BigDecimal("10.00")));
        assertThrows(ValidationException.class, () ->
                poService.addOrUpdateItem("PO-QTY-ERR", "PROD-001", -5, new BigDecimal("10.00")));
    }

    @Test
    @DisplayName("Should reject negative unit cost")
    void shouldRejectNegativeUnitCost() {
        poService.createDraftOrder("PO-COST-ERR", "SUP-001");

        assertThrows(ValidationException.class, () ->
                poService.addOrUpdateItem("PO-COST-ERR", "PROD-001", 5, new BigDecimal("-0.01")));
        assertThrows(ValidationException.class, () ->
                poService.addOrUpdateItem("PO-COST-ERR", "PROD-001", 5, null));
    }

    @Test
    @DisplayName("Should update line item when same product is added again")
    void shouldUpdateLineItemOnDuplicateProduct() {
        poService.createDraftOrder("PO-DUP-ITEM", "SUP-001");

        poService.addOrUpdateItem("PO-DUP-ITEM", "PROD-001", 10, new BigDecimal("45.00"));
        PurchaseOrder order1 = poService.getOrderByNumber("PO-DUP-ITEM").orElseThrow();
        assertEquals(1, order1.getItems().size());
        assertEquals(new BigDecimal("450.00"), order1.getTotalAmount());

        // Update with new quantity and cost
        PurchaseOrderItem updated = poService.addOrUpdateItem("PO-DUP-ITEM", "PROD-001", 20, new BigDecimal("42.50"));
        assertEquals(20, updated.getOrderedQuantity());
        assertEquals(new BigDecimal("42.50"), updated.getUnitCost());

        PurchaseOrder order2 = poService.getOrderByNumber("PO-DUP-ITEM").orElseThrow();
        assertEquals(1, order2.getItems().size(), "Should still have exactly 1 item line for PROD-001");
        assertEquals(20, order2.getTotalUnits());
        assertEquals(new BigDecimal("850.00"), order2.getTotalAmount());
    }

    @Test
    @DisplayName("Should perform exact decimal arithmetic for totals")
    void shouldPerformExactDecimalArithmetic() {
        poService.createDraftOrder("PO-MATH", "SUP-001");

        poService.addOrUpdateItem("PO-MATH", "PROD-001", 3, new BigDecimal("19.99"));
        poService.addOrUpdateItem("PO-MATH", "PROD-002", 2, new BigDecimal("12.50"));

        PurchaseOrder order = poService.getOrderByNumber("PO-MATH").orElseThrow();
        // 3 * 19.99 = 59.97 + 2 * 12.50 = 25.00 => 84.97
        assertEquals(new BigDecimal("84.97"), order.getTotalAmount());
        assertEquals(5, order.getTotalUnits());
    }

    @Test
    @DisplayName("Should remove line item from draft order")
    void shouldRemoveLineItemFromDraft() {
        poService.createDraftOrder("PO-DEL-ITEM", "SUP-001");
        poService.addOrUpdateItem("PO-DEL-ITEM", "PROD-001", 5, new BigDecimal("10.00"));
        poService.addOrUpdateItem("PO-DEL-ITEM", "PROD-002", 3, new BigDecimal("15.00"));

        boolean removed = poService.removeItem("PO-DEL-ITEM", "PROD-001");
        assertTrue(removed);

        PurchaseOrder order = poService.getOrderByNumber("PO-DEL-ITEM").orElseThrow();
        assertEquals(1, order.getItems().size());
        assertEquals("PROD-002", order.getItems().get(0).getProductSku());
        assertEquals(new BigDecimal("45.00"), order.getTotalAmount());
    }

    @Test
    @DisplayName("Should reject removing product that is not in order")
    void shouldRejectRemovingNonexistentLineItem() {
        poService.createDraftOrder("PO-DEL-ABSENT", "SUP-001");
        poService.addOrUpdateItem("PO-DEL-ABSENT", "PROD-001", 5, new BigDecimal("10.00"));

        ValidationException ex = assertThrows(ValidationException.class, () ->
                poService.removeItem("PO-DEL-ABSENT", "PROD-002"));
        assertTrue(ex.getMessage().contains("is not present on purchase order"));
    }

    @Test
    @DisplayName("Should reject placing an empty purchase order")
    void shouldRejectPlacingEmptyOrder() {
        poService.createDraftOrder("PO-EMPTY", "SUP-001");

        ValidationException ex = assertThrows(ValidationException.class, () ->
                poService.placeOrder("PO-EMPTY"));
        assertTrue(ex.getMessage().contains("no line items"));
    }

    @Test
    @DisplayName("Should place valid nonempty draft order")
    void shouldPlaceValidOrder() {
        poService.createDraftOrder("PO-PLACE-OK", "SUP-001");
        poService.addOrUpdateItem("PO-PLACE-OK", "PROD-001", 10, new BigDecimal("50.00"));

        PurchaseOrder placed = poService.placeOrder("PO-PLACE-OK");
        assertEquals(PurchaseOrderStatus.PLACED, placed.getStatus());

        PurchaseOrder retrieved = poService.getOrderByNumber("PO-PLACE-OK").orElseThrow();
        assertEquals(PurchaseOrderStatus.PLACED, retrieved.getStatus());
    }

    @Test
    @DisplayName("Should reject placing or modifying an already placed order")
    void shouldRejectModifyingPlacedOrder() {
        poService.createDraftOrder("PO-PLACED-LOCKED", "SUP-001");
        poService.addOrUpdateItem("PO-PLACED-LOCKED", "PROD-001", 5, new BigDecimal("20.00"));
        poService.placeOrder("PO-PLACED-LOCKED");

        // Placing again
        assertThrows(ValidationException.class, () -> poService.placeOrder("PO-PLACED-LOCKED"));

        // Adding line item
        assertThrows(ValidationException.class, () ->
                poService.addOrUpdateItem("PO-PLACED-LOCKED", "PROD-002", 2, new BigDecimal("10.00")));

        // Removing line item
        assertThrows(ValidationException.class, () ->
                poService.removeItem("PO-PLACED-LOCKED", "PROD-001"));

        // Cancelling placed order
        assertThrows(ValidationException.class, () ->
                poService.cancelOrder("PO-PLACED-LOCKED"));
    }

    @Test
    @DisplayName("Should cancel draft order")
    void shouldCancelDraftOrder() {
        poService.createDraftOrder("PO-CANCEL-OK", "SUP-001");

        PurchaseOrder cancelled = poService.cancelOrder("PO-CANCEL-OK");
        assertEquals(PurchaseOrderStatus.CANCELLED, cancelled.getStatus());

        // Cancel again rejected
        assertThrows(ValidationException.class, () -> poService.cancelOrder("PO-CANCEL-OK"));

        // Place cancelled rejected
        assertThrows(ValidationException.class, () -> poService.placeOrder("PO-CANCEL-OK"));

        // Modify cancelled rejected
        assertThrows(ValidationException.class, () ->
                poService.addOrUpdateItem("PO-CANCEL-OK", "PROD-001", 5, new BigDecimal("10.00")));
    }

    @Test
    @DisplayName("Should restrict deleting supplier when referenced by purchase orders")
    void shouldRestrictDeletingSupplierReferencedByPO() {
        poService.createDraftOrder("PO-REF-SUP", "SUP-001");

        ValidationException ex = assertThrows(ValidationException.class, () ->
                supplierService.deleteSupplierByCode("SUP-001"));
        assertTrue(ex.getMessage().contains("referenced by one or more purchase orders"));
    }

    @Test
    @DisplayName("Should restrict deleting product when referenced by purchase order items")
    void shouldRestrictDeletingProductReferencedByPO() {
        poService.createDraftOrder("PO-REF-PROD", "SUP-001");
        poService.addOrUpdateItem("PO-REF-PROD", "PROD-001", 10, new BigDecimal("40.00"));

        ValidationException ex = assertThrows(ValidationException.class, () ->
                productService.deleteProductBySku("PROD-001"));
        assertTrue(ex.getMessage().contains("referenced by one or more purchase order line items"));
    }

    @Test
    @DisplayName("Product stock quantities must remain completely UNTOUCHED throughout Phase 13A")
    void productStockQuantitiesMustRemainUntouched() {
        int initialQty1 = product1.getQuantity();
        int initialQty2 = product2.getQuantity();

        // 1. Create order
        poService.createDraftOrder("PO-STOCK-CHECK", "SUP-001");
        assertEquals(initialQty1, productRepository.findBySku("PROD-001").orElseThrow().getQuantity());
        assertEquals(initialQty2, productRepository.findBySku("PROD-002").orElseThrow().getQuantity());

        // 2. Add line items
        poService.addOrUpdateItem("PO-STOCK-CHECK", "PROD-001", 100, new BigDecimal("50.00"));
        poService.addOrUpdateItem("PO-STOCK-CHECK", "PROD-002", 200, new BigDecimal("20.00"));
        assertEquals(initialQty1, productRepository.findBySku("PROD-001").orElseThrow().getQuantity());
        assertEquals(initialQty2, productRepository.findBySku("PROD-002").orElseThrow().getQuantity());

        // 3. Remove line item
        poService.removeItem("PO-STOCK-CHECK", "PROD-002");
        assertEquals(initialQty1, productRepository.findBySku("PROD-001").orElseThrow().getQuantity());
        assertEquals(initialQty2, productRepository.findBySku("PROD-002").orElseThrow().getQuantity());

        // 4. Place order
        poService.placeOrder("PO-STOCK-CHECK");
        assertEquals(initialQty1, productRepository.findBySku("PROD-001").orElseThrow().getQuantity());
        assertEquals(initialQty2, productRepository.findBySku("PROD-002").orElseThrow().getQuantity());

        // 5. Cancel another order
        poService.createDraftOrder("PO-STOCK-CANCEL", "SUP-001");
        poService.addOrUpdateItem("PO-STOCK-CANCEL", "PROD-001", 50, new BigDecimal("50.00"));
        poService.cancelOrder("PO-STOCK-CANCEL");
        assertEquals(initialQty1, productRepository.findBySku("PROD-001").orElseThrow().getQuantity());
        assertEquals(initialQty2, productRepository.findBySku("PROD-002").orElseThrow().getQuantity());
    }
}
